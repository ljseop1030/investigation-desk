// 배속의 정의. 규칙 파일 다섯 곳에 같은 두 줄이 흩어져 있던 것을 모았다.
//
// tempo는 기다림에만 건다. 답을 기다리는 시간은 줄이고, 말풍선 사이 간격처럼
// 사람이 자판을 치는 속도는 건드리지 않는다. 배속으로 줄이면 tick(1초)보다
// 짧아져서 여러 줄이 한꺼번에 쏟아진다.
//
// 부르는 쪽이 wait과 beat 중 무엇을 쓰는지가 그 값이 어느 쪽인지에 대한 답이다.
// 콘텐츠도 코드 상수도 전부 초 단위로 적고, 밀리초 환산은 여기서만 한다.

export function createTiming({ tempo = 1, random = Math.random } = {}) {
  return {
    // 범위에서 하나 뽑는다. [lo, hi] 초.
    pick: ([lo, hi]) => lo + random() * (hi - lo),

    // 기다림. 배속에 눌린다.
    wait: (sec) => (sec * 1000) / tempo,

    // 말하는 속도. 배속과 무관하다.
    beat: (sec) => sec * 1000,
  };
}